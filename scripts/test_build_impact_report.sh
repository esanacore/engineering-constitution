#!/usr/bin/env bash
set -euo pipefail

# Tests for scripts/build_impact_report.sh, which creates an adopter's
# Constitution Impact Report from the template and rewrites its generated
# Adoption Snapshot block from facts measured in the repository.

script_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
builder="$script_dir/build_impact_report.sh"

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
fail() { echo "FAIL: $*"; exit 1; }

# Fixture commits must not depend on the machine's git identity or config.
export GIT_AUTHOR_NAME=test GIT_AUTHOR_EMAIL=test@example.invalid
export GIT_COMMITTER_NAME=test GIT_COMMITTER_EMAIL=test@example.invalid
export GIT_CONFIG_GLOBAL=/dev/null GIT_CONFIG_SYSTEM=/dev/null

repo="$tmp/widget"
report="$repo/docs/CONSTITUTION_IMPACT.md"
value_of() { sed -nE "s/^\| $1 \| (.*) \| [^|]*\|\$/\1/p" "${2:-$report}"; }

# A small adopter: pinned constitution, two workflows, an ADR, two session
# summaries, a traceability matrix, an OTS inventory, a changelog, a TODO.
mkdir -p "$repo/constitution" "$repo/.github/workflows" "$repo/docs/adr" "$repo/docs/sessions"
printf '1.56.0\n' > "$repo/constitution/VERSION"
: > "$repo/.github/workflows/constitution-tests.yml"
: > "$repo/.github/workflows/constitution-compliance.yaml"
: > "$repo/.github/workflows/ci.yml"
printf '# ADR\n' > "$repo/docs/adr/0001-record-decisions.md"
printf '# Index\n' > "$repo/docs/adr/README.md"
printf '# S\n' > "$repo/docs/sessions/2026-01-12-adopt.md"
printf '# S\n' > "$repo/docs/sessions/2026-02-01-login.md"
printf '# T\n' > "$repo/docs/sessions/TEMPLATE.md"
cat > "$repo/docs/REQUIREMENTS_TRACEABILITY.md" <<'DOC'
| Requirement ID | Level | Description | Acceptance Criteria | Verifying Tests | Status |
| --- | --- | --- | --- | --- | --- |
| FR-001 | MUST | Log in | FR-001-AC-1 | test_login | Verified |
| FR-002 | MUST | Log out | FR-002-AC-1 | none | In Progress |
| **NFR-001** | MUST | Fast | NFR-001-AC-1 | test_perf | Verified |
| FR-003 | MUST | `<requirement description>` | `<x>` | `<y>` | Not Started |

| Metric | Count |
| --- | --- |
| Verified | 2 |
DOC
cat > "$repo/docs/OTS_SOFTWARE.md" <<'DOC'
| Component ID | Name | Status |
| --- | --- | --- |
| OTS-001 | express | Active |
| OTS-002 | `<name exactly as declared in the manifest>` | Active |
| OTS-003 | left-pad | Removed |
DOC
printf '# Test Plan\n\n- Full suite: `npm test | tee out.log`\n' > "$repo/docs/TEST_PLAN.md"
printf '# Changelog\n\n## Unreleased\n\n## [1.1.0] - 2026-02-01\n\n## 1.0.0 - 2026-01-12\n\n### Added\n' > "$repo/CHANGELOG.md"
printf '# TODO\n\n- [ ] one\n  - [~] two\n- [x] three\n- plain\n' > "$repo/TODO.md"
git -C "$repo" init -q -b main
git -C "$repo" add -A
GIT_AUTHOR_DATE=2026-01-12T10:00:00 GIT_COMMITTER_DATE=2026-01-12T10:00:00 git -C "$repo" commit -q -m "adopt"
printf '1.56.1\n' > "$repo/constitution/VERSION"
git -C "$repo" add -A
GIT_AUTHOR_DATE=2026-03-01T10:00:00 GIT_COMMITTER_DATE=2026-03-01T10:00:00 git -C "$repo" commit -q -m "bump"

echo "Test 1: a missing report is created from the template, titled, with its snapshot written"
out=$("$builder" --date 2026-11-16 "$repo")
[ -f "$report" ] || fail "report not created"
[ "$(head -n 1 "$report")" = "# Constitution Impact: widget" ] || fail "title not filled: $(head -n 1 "$report")"
grep -q '^Created docs/CONSTITUTION_IMPACT.md' <<< "$out" || fail "creation not reported: $out"
grep -q 'still template text' <<< "$out" || fail "no reminder to fill in the hand-written sections"
grep -qF '_Generated by `build_impact_report.sh` on 2026-11-16.' "$report" || fail "date stamp missing"
grep -q 'Not generated yet' "$report" && fail "template's snapshot text was left in place"
for h in "## Summary" "## What Changed" "## Catches" "## What It Cost" "## Not Yet Adopted"; do
  grep -qxF "$h" "$report" || fail "template section lost: $h"
done
echo "PASS"

echo "Test 2: each measure reports what the repository holds"
[ "$(value_of 'Constitution version')" = "1.56.1" ] || fail "version: $(value_of 'Constitution version')"
[ "$(value_of 'Adopted since')" = "2026-01-12" ] || fail "adopted: $(value_of 'Adopted since')"
grep -qE '^[0-9]+ of [0-9]+ required, [0-9]+ of [0-9]+ recommended' <<< "$(value_of 'Governance files')" \
  || fail "compliance: $(value_of 'Governance files')"
[ "$(value_of 'Constitution CI workflows')" = "2: compliance, tests" ] || fail "workflows: $(value_of 'Constitution CI workflows')"
[ "$(value_of 'Declared test command')" = '`npm test \| tee out.log`' ] || fail "tests: $(value_of 'Declared test command')"
[ "$(value_of 'Requirements')" = "3 traced, 2 verified" ] || fail "requirements: $(value_of 'Requirements')"
[ "$(value_of 'OTS components inventoried')" = "2" ] || fail "ots: $(value_of 'OTS components inventoried')"
[ "$(value_of 'Architecture decision records')" = "1" ] || fail "adrs: $(value_of 'Architecture decision records')"
[ "$(value_of 'Session summaries')" = "2" ] || fail "sessions: $(value_of 'Session summaries')"
[ "$(value_of 'Releases recorded')" = "2" ] || fail "releases: $(value_of 'Releases recorded')"
[ "$(value_of 'TODO items')" = "2 open, 1 done" ] || fail "todo: $(value_of 'TODO items')"
echo "PASS"

echo "Test 3: the compliance row agrees with check_compliance.sh"
ok=$(bash "$script_dir/check_compliance.sh" "$repo" 2>/dev/null | awk '/^Required:/{t=1;next} /^[^ ]/{t=0} t && $1=="OK"{n++} END{print n+0}' || true)
grep -q "^$ok of " <<< "$(value_of 'Governance files')" || fail "required OK count $ok not in: $(value_of 'Governance files')"
echo "PASS"

echo "Test 4: a rerun on a later date changes nothing"
before=$(cksum < "$report")
out=$("$builder" --date 2027-01-01 "$repo")
[ "$(cksum < "$report")" = "$before" ] || fail "a date-only difference rewrote the report"
grep -q 'is current' <<< "$out" || fail "did not report current: $out"
echo "PASS"

echo "Test 5: hand-written sections survive a refresh; only the block changes"
sed -i.bak -e 's/^<summary>$/Widget adopted the constitution in January 2026./' \
  -e 's/^- <cost>$/- Two false positives from the secrets sweep (pull request 7)./' "$report"
rm -f "$report.bak"
printf '\nTrailing note.\n' >> "$report"
printf '# S\n' > "$repo/docs/sessions/2026-03-02-third.md"
out=$("$builder" --date 2026-12-01 "$repo")
grep -q '^Refreshed the snapshot' <<< "$out" || fail "refresh not reported: $out"
[ "$(value_of 'Session summaries')" = "3" ] || fail "snapshot not refreshed"
grep -qF 'on 2026-12-01.' "$report" || fail "stamp not updated on a real change"
grep -qxF 'Widget adopted the constitution in January 2026.' "$report" || fail "summary lost"
grep -qxF -- '- Two false positives from the secrets sweep (pull request 7).' "$report" || fail "cost bullet lost"
[ "$(tail -n 1 "$report")" = "Trailing note." ] || fail "text after the block lost"
[ "$(grep -c '^| Measure | Value | Source |$' "$report")" = 1 ] || fail "snapshot table duplicated"
[ "$(grep -cxF '<!-- impact:snapshot:start -->' "$report")" = 1 ] || fail "start marker count changed"
[ "$(grep -cxF '<!-- impact:snapshot:end -->' "$report")" = 1 ] || fail "end marker count changed"
echo "PASS"

echo "Test 6: --print writes nothing and prints the snapshot"
before=$(cksum < "$report")
printf '# S\n' > "$repo/docs/sessions/2026-03-03-fourth.md"
out=$("$builder" --print --date 2026-12-02 "$repo")
[ "$(cksum < "$report")" = "$before" ] || fail "--print wrote the report"
grep -qF '| Session summaries | 4 |' <<< "$out" || fail "--print did not show the current value: $out"
grep -qF 'impact:snapshot' <<< "$out" && fail "--print emitted the markers"
mkdir -p "$tmp/fresh"
"$builder" --print "$tmp/fresh" > /dev/null
[ ! -e "$tmp/fresh/docs" ] || fail "--print created the report"
echo "PASS"

echo "Test 7: a bare directory yields honest gaps, not errors or invented numbers"
out=$("$builder" --print "$tmp/fresh")
bare="$tmp/bare.md"; printf '%s\n' "$out" > "$bare"
[ "$(value_of 'Constitution version' "$bare")" = "not found" ] || fail "version: $(value_of 'Constitution version' "$bare")"
[ "$(value_of 'Adopted since' "$bare")" = "unknown (not a git repository)" ] || fail "adopted: $(value_of 'Adopted since' "$bare")"
[ "$(value_of 'Constitution CI workflows' "$bare")" = "none" ] || fail "workflows"
for m in 'Declared test command' 'Requirements' 'OTS components inventoried' 'Architecture decision records' 'Session summaries' 'Releases recorded' 'TODO items'; do
  [ "$(value_of "$m" "$bare")" = "not present" ] || fail "$m: $(value_of "$m" "$bare")"
done
echo "PASS"

echo "Test 8: a placeholder test command is not declared; no adoption commit is unknown"
mkdir -p "$tmp/young/docs"
printf -- '- Full suite: `<command>`\n' > "$tmp/young/docs/TEST_PLAN.md"
git -C "$tmp/young" init -q -b main
git -C "$tmp/young" add -A && git -C "$tmp/young" commit -q -m init
out=$("$builder" --print "$tmp/young"); printf '%s\n' "$out" > "$bare"
[ "$(value_of 'Declared test command' "$bare")" = "not declared" ] || fail "tests: $(value_of 'Declared test command' "$bare")"
grep -q '^unknown (no commit touches' <<< "$(value_of 'Adopted since' "$bare")" || fail "adopted: $(value_of 'Adopted since' "$bare")"
echo "PASS"

echo "Test 9: a shallow clone keeps the recorded adoption date, and says unknown without one"
git clone -q --depth 1 "file://$repo" "$tmp/shallow"
out=$("$builder" --print "$tmp/shallow"); printf '%s\n' "$out" > "$bare"
grep -q '^unknown (shallow clone' <<< "$(value_of 'Adopted since' "$bare")" || fail "shallow, no report: $(value_of 'Adopted since' "$bare")"
cp "$report" "$tmp/shallow/docs/CONSTITUTION_IMPACT.md"
"$builder" "$tmp/shallow" > /dev/null
[ "$(value_of 'Adopted since' "$tmp/shallow/docs/CONSTITUTION_IMPACT.md")" = "2026-01-12" ] || fail "recorded date was erased"
echo "PASS"

echo "Test 10: missing, duplicated, or reversed markers exit 2 and leave the file alone"
broken="$tmp/broken"; mkdir -p "$broken/docs"
for body in '# Report\n\nNo markers.\n' \
            '<!-- impact:snapshot:start -->\n<!-- impact:snapshot:start -->\n<!-- impact:snapshot:end -->\n' \
            '<!-- impact:snapshot:end -->\nold\n<!-- impact:snapshot:start -->\n' \
            '<!-- impact:snapshot:start -->\nno end\n'; do
  # shellcheck disable=SC2059
  printf "$body" > "$broken/docs/CONSTITUTION_IMPACT.md"
  before=$(cksum < "$broken/docs/CONSTITUTION_IMPACT.md")
  status=0; "$builder" "$broken" > /dev/null 2>&1 || status=$?
  [ "$status" = 2 ] || fail "broken markers exited $status, expected 2"
  [ "$(cksum < "$broken/docs/CONSTITUTION_IMPACT.md")" = "$before" ] || fail "a rejected report was modified"
done
echo "PASS"

echo "Test 11: usage errors exit 2"
for args in "--bogus" "--file" "--date" "--date 16-11-2026" "$repo $repo" "$tmp/missing"; do
  status=0
  # shellcheck disable=SC2086
  "$builder" $args > /dev/null 2>&1 || status=$?
  [ "$status" = 2 ] || fail "'$args' exited $status, expected 2"
done
"$builder" --help | grep -q '^Usage:' || fail "--help prints no usage"
echo "PASS"

echo "Test 12: --file and --constitution-dir select other locations"
alt="$tmp/alt"; mkdir -p "$alt/vendor/ec"
printf '2.0.0\n' > "$alt/vendor/ec/VERSION"
"$builder" --file docs/governance/IMPACT.md --constitution-dir vendor/ec "$alt" > /dev/null
[ -f "$alt/docs/governance/IMPACT.md" ] || fail "--file not honored"
[ "$(value_of 'Constitution version' "$alt/docs/governance/IMPACT.md")" = "2.0.0" ] || fail "--constitution-dir not honored"
grep -qF '`vendor/ec/VERSION`' "$alt/docs/governance/IMPACT.md" || fail "source column does not name the chosen directory"
echo "PASS"

echo "Test 13: a CRLF report is refreshed and keeps its hand-written lines"
crlf="$tmp/crlf"; mkdir -p "$crlf/docs"
printf '# Report\r\n\r\n<!-- impact:snapshot:start -->\r\nold\r\n<!-- impact:snapshot:end -->\r\n\r\nKept.\r\n' > "$crlf/docs/CONSTITUTION_IMPACT.md"
"$builder" "$crlf" > /dev/null || fail "CRLF markers not recognized"
grep -q '^| Measure | Value | Source |' "$crlf/docs/CONSTITUTION_IMPACT.md" || fail "snapshot not written"
grep -q '^old' "$crlf/docs/CONSTITUTION_IMPACT.md" && fail "old block content left behind"
grep -q '^Kept\.' "$crlf/docs/CONSTITUTION_IMPACT.md" || fail "hand-written line lost"
echo "PASS"

echo "Test 14: a directory name with sed-special characters becomes the title unharmed"
odd="$tmp/a&b|c"; mkdir -p "$odd"
"$builder" "$odd" > /dev/null
[ "$(head -n 1 "$odd/docs/CONSTITUTION_IMPACT.md")" = "# Constitution Impact: a&b|c" ] || fail "title: $(head -n 1 "$odd/docs/CONSTITUTION_IMPACT.md")"
echo "PASS"

echo "All build_impact_report tests passed."
